"""Deterministic physical-wellness recommendations for Mind–Body insights.

The backend pattern engine owns pattern detection; this module only turns
already-validated patterns into supportive, proportionate suggestions. It makes
no LLM call, so it is fully testable and cannot invent measurements.

Safety rules baked in here:
* no medical claims, diagnosis, or causation;
* activity suggestions stay light/comfortable;
* no calorie restriction, sleep restriction, or fluid-loading advice;
* every recommendation is grounded in a pattern that was actually detected.
"""

from __future__ import annotations

import re
from typing import Any

from app.core.llm.client import LLMClient, build_llm_client
from app.logging import get_logger
from app.schemas.wellness import (
    PhysicalInsightRequest,
    PhysicalInsightResponse,
    WellnessRecommendation,
)

log = get_logger(__name__)

