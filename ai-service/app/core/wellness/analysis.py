"""Personalised wellness analysis for the three in-app analysis buttons.

The backend computes every measurement and the history comparison; this module
turns those aggregates into a narrative, focus areas, recommendations and next
actions. Wording may be re-generated by the LLM, but the *numbers* always come
from the backend payload, so nothing here can invent a measurement.

Safety rules baked in:
* no diagnosis, medication, calorie restriction, sleep restriction or fluid
  loading;
* targets are gentle ranges, never medical prescriptions;
* the LLM may only rephrase — its output is rejected if it contains digits or
  medical claims, in which case the rule wording is returned.
"""

from __future__ import annotations

import re
from typing import Any

from app.core.llm.client import LLMClient, build_llm_client
from app.logging import get_logger
from app.schemas.analysis import (
    AnalysisMetric,
    WellnessAnalysisRequest,
    WellnessAnalysisResponse,
)
from app.schemas.wellness import WellnessRecommendation

log = get_logger(__name__)

_RULES_NOTE = (
    "Generated from your own recorded data by the wellness rules engine. "
    "Supportive guidance, not a medical assessment."
)
_LLM_NOTE = (
    "AI-personalised wording grounded in your own recorded data. "
    "No measurements were invented and no medical assessment was made."
)

_BANNED_TERMS = (
    "diagnos",
    "prescrib",
    "medication",
    "dosage",
    "disorder",
    "cure",
    "calorie",
    "skip meals",
    "sleep restriction",
    "force yourself",
    "deficit",
)

_MAX_RECOMMENDATIONS = 4


def _metrics(payload: WellnessAnalysisRequest) -> dict[str, AnalysisMetric]:
    return {metric.key: metric for metric in payload.metrics}


def _value(payload: WellnessAnalysisRequest) -> dict[str, float]:
    return {metric.key: metric.value for metric in payload.metrics}


def _rec(rec_id: str, title: str, description: str, category: str) -> WellnessRecommendation:
    return WellnessRecommendation(
        id=rec_id,
        title=title,
        description=description,
        category=category,
        source="AI_SERVICE",
    )


def _focus_areas(payload: WellnessAnalysisRequest) -> list[str]:
    """Areas worth attention, most important first."""
    v = _value(payload)
    focus: list[str] = []

    if payload.comparison.declined:
        focus.append("reversing recent declines")
    if v.get("stress_level", 0) >= 60:
        focus.append("stress regulation")
    if "sleep_hours_avg" in v and v["sleep_hours_avg"] < 7:
        focus.append("sleep duration")
    if "steps_avg" in v and v["steps_avg"] < 7000:
        focus.append("daily movement")
    if "active_minutes_avg" in v and v["active_minutes_avg"] < 30:
        focus.append("active minutes")
    if "hydration_ml_avg" in v and 0 < v["hydration_ml_avg"] < 2000:
        focus.append("hydration")
    if 0 < v.get("wellness_score", 100) < 60:
        focus.append("mood and emotional wellbeing")
    if 0 < v.get("lifestyle_score", 100) < 60:
        focus.append("daily routine consistency")

    if not focus:
        focus.append("keeping your current balance")
    return focus[:4]


def _recommendations(payload: WellnessAnalysisRequest) -> list[WellnessRecommendation]:
    v = _value(payload)
    recs: list[WellnessRecommendation] = []

    stress = v.get("stress_level")
    if stress is not None and stress >= 60:
        recs.append(
            _rec(
                "slow_breathing",
                "Two minutes of slow breathing",
                "Try breathing in for a slow count of four and out for six, twice a day — "
                "once when you wake and once before your evening wind-down. It is a short "
                "reset you can repeat whenever tension builds.",
                "MENTAL",
            )
        )

    sleep = v.get("sleep_hours_avg")
    if sleep is not None and sleep < 7:
        recs.append(
            _rec(
                "steady_wind_down",
                "A repeatable wind-down before bed",
                "Aim for roughly seven to eight hours in bed. Pick a fixed wind-down "
                "time about forty-five minutes before you want to sleep and keep your "
                "wake time steady, even after a short night.",
                "SLEEP",
            )
        )
    elif sleep is not None and 7 <= sleep <= 9:
        recs.append(
            _rec(
                "protect_sleep_window",
                "Protect the sleep window you already have",
                "Your recent sleep duration sits in a healthy range. Guard the same bedtime "
                "on busy days rather than catching up at the weekend.",
                "SLEEP",
            )
        )

    hydration = v.get("hydration_ml_avg")
    if hydration is not None and hydration < 2000:
        recs.append(
            _rec(
                "hydration_rhythm",
                "Build a steady hydration rhythm",
                "Rather than one large drink, spread water through the day: a glass with "
                "each meal and one beside your desk or bag. That usually closes most of the "
                "gap without effort.",
                "HYDRATION",
            )
        )

    steps = v.get("steps_avg")
    active = v.get("active_minutes_avg")
    if steps is not None and steps < 7000:
        recs.append(
            _rec(
                "two_short_walks",
                "Two short walks beat one long one",
                "Add a ten-minute walk after a meal and one more whenever you would "
                "otherwise sit. Two short walks are easier to keep than a single long session.",
                "ACTIVITY",
            )
        )
    elif active is not None and active < 30:
        recs.append(
            _rec(
                "active_breaks",
                "Break up long sitting",
                "Stand and move for two or three minutes every hour. Small breaks across "
                "the day add up without needing a workout.",
                "ACTIVITY",
            )
        )

    if 0 < v.get("wellness_score", 100) < 60:
        recs.append(
            _rec(
                "daily_check_in",
                "One honest check-in a day",
                "Log how you feel once a day, even briefly. The pattern matters more than "
                "any single entry, and it makes your next analysis more personal.",
                "MENTAL",
            )
        )

    if not recs:
        recs.append(
            _rec(
                "maintain_routine",
                "Keep the routine that is working",
                "Your recent data looks balanced. Keep the same sleep, movement and "
                "check-in rhythm, and notice which days feel easiest to repeat.",
                "GENERAL",
            )
        )

    return recs[:_MAX_RECOMMENDATIONS]


def _next_actions(payload: WellnessAnalysisRequest) -> list[str]:
    """Concrete, realistic daily or weekly targets based on the actual data."""
    v = _value(payload)
    actions: list[str] = []

    if payload.comparison.declined:
        actions.append(
            "This week: focus on " + ", ".join(payload.comparison.declined[:2]) + " first."
        )
    sleep = v.get("sleep_hours_avg")
    if sleep is not None and sleep < 7:
        actions.append("Daily: same wind-down time, aiming for seven to eight hours in bed.")
    steps = v.get("steps_avg")
    if steps is not None:
        target = 7000 if steps < 7000 else int(round(steps + 500))
        actions.append(f"Daily: about {target} steps — two short walks is enough.")
    hydration = v.get("hydration_ml_avg")
    if hydration is not None and hydration < 2000:
        actions.append("Daily: water with each meal, plus one refill in the afternoon.")
    stress = v.get("stress_level")
    if stress is not None and stress >= 60:
        actions.append("Daily: two slow-breathing breaks, morning and evening.")
    if payload.comparison.improved:
        actions.append(
            "Keep doing: " + ", ".join(payload.comparison.improved[:2]) + " — it is trending up."
        )
    if not actions:
        actions.append("This week: keep your current routine and check in daily.")

    return actions[:5]


def _cap(text: str) -> str:
    return text[:1].upper() + text[1:] if text else text


def _narrative(payload: WellnessAnalysisRequest, focus: list[str]) -> str:
    label = {
        "MENTAL": "mental wellness",
        "PHYSICAL": "physical wellness",
        "COMBINED": "mental and physical wellness",
    }[payload.type]
    parts: list[str] = [f"This {label} analysis covers the last {payload.window_days} days."]

    if payload.comparison.has_previous:
        days = payload.comparison.days_since_previous
        when = f"{days} days ago" if days and days > 0 else "your previous analysis"
        if payload.comparison.improved:
            parts.append(
                f"Compared with {when}, "
                f"{', '.join(payload.comparison.improved[:2])} improved."
            )
        if payload.comparison.declined:
            # Mid-sentence this reads naturally; at the start it needs a capital.
            declined = ", ".join(payload.comparison.declined[:2])
            if payload.comparison.improved:
                parts.append(f"{declined} moved in the other direction.")
            else:
                parts.append(f"{_cap(declined)} moved in the other direction.")
        if not payload.comparison.improved and not payload.comparison.declined:
            parts.append(f"Your readings are broadly unchanged since {when}.")
    else:
        parts.append(
            "This is the first stored analysis, so there is nothing to compare against yet."
        )

    if payload.patterns:
        parts.append("Observed: " + payload.patterns[0].rstrip(".") + ".")
    parts.append("Next focus: " + ", ".join(focus[:2]) + ".")
    return " ".join(parts)


def build_analysis(payload: WellnessAnalysisRequest) -> WellnessAnalysisResponse:
    """Deterministic analysis — used directly and as the LLM fallback."""
    focus = _focus_areas(payload)
    return WellnessAnalysisResponse(
        narrative=_narrative(payload, focus),
        recommendations=_recommendations(payload),
        focus_areas=focus,
        next_actions=_next_actions(payload),
        generated_by="rules",
        note=_RULES_NOTE,
    )


# ── optional LLM wording ────────────────────────────────────────────────

_WORDING_SCHEMA = {
    "type": "OBJECT",
    "properties": {
        "narrative": {"type": "STRING"},
        "recommendations": {
            "type": "ARRAY",
            "items": {
                "type": "OBJECT",
                "properties": {
                    "id": {"type": "STRING"},
                    "title": {"type": "STRING"},
                    "description": {"type": "STRING"},
                    "category": {"type": "STRING"},
                },
                "required": ["id", "title", "description", "category"],
            },
        },
    },
    "required": ["narrative", "recommendations"],
}

_SYSTEM_PROMPT = """You write short, supportive guidance for a wellbeing app.

The backend has already measured everything and detected the patterns below.
Rewrite the guidance in warm, plain language for the analysis type given.

Rules:
- Stay strictly within the supplied metrics and patterns; never add a symptom,
  cause, diagnosis or new measurement.
- Do not use any digits at all.
- No calorie restriction, sleep restriction, fluid loading, medication or
  diagnosis.
- The narrative is at most three sentences.
- Each recommendation title is under 60 characters, its description under 200.
- Return at most three recommendations, addressing declined areas first.
"""


def _user_block(payload: WellnessAnalysisRequest) -> str:
    lines: list[str] = [f"Analysis type: {payload.type}", f"Window: last {payload.window_days} days"]
    if payload.metrics:
        lines.append(
            "Metrics (authoritative): "
            + "; ".join(
                f"{m.label} = {m.value:g}{(' ' + m.unit) if m.unit else ''}"
                for m in payload.metrics
            )
        )
    if payload.patterns:
        lines.append("Detected patterns: " + "; ".join(payload.patterns))
    comp = payload.comparison
    if comp.has_previous:
        lines.append(
            "Comparison with previous analysis: "
            f"improved={comp.improved or 'none'}; declined={comp.declined or 'none'}; "
            f"unchanged={comp.unchanged or 'none'}"
        )
    else:
        lines.append("No previous analysis: this is the first one.")
    if payload.existing_recommendations:
        lines.append("Already shown by the rules: " + "; ".join(payload.existing_recommendations))
    return "\n".join(lines)


def _validate(raw: dict[str, Any]) -> WellnessAnalysisResponse | None:
    narrative = str(raw.get("narrative") or "").strip()
    if not narrative or re.search(r"\d", narrative):
        return None
    text = narrative.lower()
    if any(term in text for term in _BANNED_TERMS):
        return None

    accepted: list[WellnessRecommendation] = []
    seen: set[str] = set()
    for item in raw.get("recommendations") or []:
        if not isinstance(item, dict):
            continue
        rec_id = re.sub(r"[^a-z0-9_]", "_", str(item.get("id") or "").strip().lower())
        title = str(item.get("title") or "").strip()
        description = str(item.get("description") or "").strip()
        category = str(item.get("category") or "WELLNESS").strip().upper()[:32]
        if not rec_id or not title or not description or rec_id in seen:
            continue
        body = f"{title} {description}".lower()
        if re.search(r"\d", body) or any(term in body for term in _BANNED_TERMS):
            continue
        seen.add(rec_id)
        accepted.append(
            WellnessRecommendation(
                id=f"llm_{rec_id}",
                title=title[:120],
                description=description[:600],
                category=category,
                source="AI_SERVICE",
            )
        )
        if len(accepted) >= 3:
            break

    if not accepted:
        return None

    return WellnessAnalysisResponse(
        narrative=narrative[:1200],
        recommendations=accepted,
        focus_areas=[],
        next_actions=[],
        generated_by="llm",
        note=_LLM_NOTE,
    )


async def analyze_with_llm(
    payload: WellnessAnalysisRequest, llm: LLMClient | None = None
) -> WellnessAnalysisResponse:
    """Rules-based analysis, optionally re-worded by the LLM.

    The rule result always supplies focus areas and numeric next actions; the
    LLM only replaces narrative and recommendation wording. Any transport,
    configuration or validation failure returns the rule result unchanged.
    """
    base = build_analysis(payload)

    client = llm
    if client is None:
        try:
            client = build_llm_client()
        except Exception:  # noqa: BLE001
            return base

    try:
        if not await client.is_available():
            return base
        raw = await client.complete_json(
            _SYSTEM_PROMPT, _user_block(payload), _WORDING_SCHEMA, max_tokens=700
        )
        validated = _validate(raw or {})
        if validated is None:
            log.warning("wellness_analysis_wording_fallback", analysis_type=payload.type)
            return base
        return WellnessAnalysisResponse(
            narrative=validated.narrative,
            recommendations=validated.recommendations,
            focus_areas=base.focus_areas,
            next_actions=base.next_actions,
            generated_by="llm",
            note=_LLM_NOTE,
        )
    except Exception as exc:  # noqa: BLE001
        log.warning("wellness_analysis_llm_unavailable", error=str(exc)[:200])
        return base
