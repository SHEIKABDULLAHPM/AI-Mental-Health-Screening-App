import 'package:flutter/material.dart';
import 'package:go_router/go_router.dart';

import 'package:mindease/core/storage/app_preferences.dart';
import 'package:mindease/core/theme/app_colors.dart';
import 'package:mindease/core/theme/app_spacing.dart';
import 'package:mindease/shared/widgets/app_backdrop.dart';
import 'package:mindease/shared/widgets/app_button.dart';
import 'package:mindease/shared/widgets/app_checkbox_tile.dart';
import 'package:mindease/shared/widgets/app_section_card.dart';
import 'package:mindease/shared/widgets/form_error_banner.dart';

/// Collects the four required consents before AI screening begins.
class PrivacyConsentScreen extends StatefulWidget {
  const PrivacyConsentScreen({super.key});

  @override
  State<PrivacyConsentScreen> createState() => _PrivacyConsentScreenState();
}

class _PrivacyConsentScreenState extends State<PrivacyConsentScreen> {
  bool _privacy = false;
  bool _terms = false;
  bool _aiAnalysis = false;
  bool _storage = false;

  bool _triedSubmit = false;
  bool _busy = false;
  String? _error;

  bool get _allConsented => _privacy && _terms && _aiAnalysis && _storage;

  Future<void> _accept() async {
    setState(() => _triedSubmit = true);
    if (!_allConsented) return;

    setState(() {
      _busy = true;
      _error = null;
    });
    await Future.delayed(const Duration(milliseconds: 900));
    final prefs = await AppPreferences.load();
    await prefs.setConsent(true);
    if (!mounted) return;
    context.go('/permissions');
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final showAll = _triedSubmit && !_allConsented;
    return Scaffold(
      appBar: AppBar(title: const Text('Your Consent Matters')),
      body: AppBackdrop(
        child: SafeArea(
          child: Column(
            children: [
              Expanded(
                child: SingleChildScrollView(
                  padding: const EdgeInsets.fromLTRB(
                    AppSpacing.lg,
                    8,
                    AppSpacing.lg,
                    AppSpacing.md,
                  ),
                  child: Center(
                    child: ConstrainedBox(
                      constraints: const BoxConstraints(maxWidth: 480),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.stretch,
                        children: [
                          Text(
                            'Before we begin',
                            style: theme.textTheme.headlineSmall?.copyWith(
                              fontWeight: FontWeight.w700,
                            ),
                          ),
                          const SizedBox(height: 6),
                          Text(
                            'MindEase uses AI to analyse your screening '
                            'responses and create a personalised wellness '
                            'profile. Please read the following and give your '
                            'explicit consent.',
                            style: theme.textTheme.bodyMedium?.copyWith(
                              color: theme.colorScheme.onSurfaceVariant,
                              height: 1.5,
                            ),
                          ),
                          const SizedBox(height: AppSpacing.lg),
                          AppSectionCard(
                            icon: Icons.shield_outlined,
                            iconColor: theme.colorScheme.primary,
                            title: 'Privacy Policy',
                            subtitle:
                                'What we collect, why, and how long we keep it. '
                                'You can revoke consent and request deletion any time.',
                          ),
                          const SizedBox(height: AppSpacing.md),
                          AppSectionCard(
                            icon: Icons.description_outlined,
                            iconColor: theme.colorScheme.tertiary,
                            title: 'Terms & Conditions',
                            subtitle: 'Rules for using MindEase, including '
                                'appropriate usage and your responsibilities.',
                          ),
                          const SizedBox(height: AppSpacing.md),
                          AppSectionCard(
                            icon: Icons.auto_awesome_outlined,
                            iconColor: theme.colorScheme.secondary,
                            title: 'AI Disclaimer',
                            subtitle: 'Insights are generated by AI and are '
                                'guidance only — never a diagnosis and never a '
                                'substitute for professional care.',
                          ),
                          const SizedBox(height: AppSpacing.md),
                          const AppSectionCard(
                            icon: Icons.dns_outlined,
                            iconColor: AppColors.success,
                            title: 'Data Collection',
                            subtitle: 'Your responses, check-ins and gauge '
                                'readings power your personalised guidance.',
                          ),
                          const SizedBox(height: AppSpacing.md),
                          const AppSectionCard(
                            icon: Icons.lock_outline,
                            iconColor: AppColors.info,
                            title: 'Secure Storage',
                            subtitle: 'All data is encrypted in transit and '
                                'at rest, stored on protected servers.',
                          ),
                          const SizedBox(height: AppSpacing.lg),
                          if (_error != null) ...[
                            FormErrorBanner(message: _error!),
                            const SizedBox(height: AppSpacing.md),
                          ],
                        ],
                      ),
                    ),
                  ),
                ),
              ),
              Padding(
                padding: const EdgeInsets.fromLTRB(
                  AppSpacing.lg,
                  0,
                  AppSpacing.lg,
                  AppSpacing.lg,
                ),
                child: Center(
                  child: ConstrainedBox(
                    constraints: const BoxConstraints(maxWidth: 480),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.stretch,
                      children: [
                        AppCheckboxTile(
                          title: 'I accept the Privacy Policy',
                          value: _privacy,
                          error: showAll && !_privacy ? 'Required' : null,
                          onChanged: (v) => setState(() => _privacy = v),
                        ),
                        AppCheckboxTile(
                          title: 'I accept the Terms & Conditions',
                          value: _terms,
                          error: showAll && !_terms ? 'Required' : null,
                          onChanged: (v) => setState(() => _terms = v),
                        ),
                        AppCheckboxTile(
                          title: 'I consent to AI analysis of my responses',
                          value: _aiAnalysis,
                          error: showAll && !_aiAnalysis ? 'Required' : null,
                          onChanged: (v) => setState(() => _aiAnalysis = v),
                        ),
                        AppCheckboxTile(
                          title: 'I consent to secure storage of my data',
                          value: _storage,
                          error: showAll && !_storage ? 'Required' : null,
                          onChanged: (v) => setState(() => _storage = v),
                        ),
                        const SizedBox(height: AppSpacing.lg),
                        AppButton(
                          label: 'Accept & Continue',
                          loading: _busy,
                          onPressed: _accept,
                        ),
                        const SizedBox(height: AppSpacing.sm),
                        AppButton(
                          label: 'Back',
                          variant: AppButtonVariant.text,
                          onPressed:
                              _busy ? null : () => context.go('/register'),
                        ),
                      ],
                    ),
                  ),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
