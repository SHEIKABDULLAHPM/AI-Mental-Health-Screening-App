def recommend(payload: PhysicalInsightRequest) -> PhysicalInsightResponse:
    """Build recommendations from validated patterns only."""

    existing = set(payload.existing_recommendations)
    recommendations: list[WellnessRecommendation] = []
    seen: set[str] = set()

    # Attention patterns first so limited slots surface what matters most.
    ordered = sorted(
        payload.patterns,
        key=lambda pattern: 0 if pattern.severity.upper() == "ATTENTION" else 1,
    )

    for pattern in ordered:
        mapping = _PATTERN_RECOMMENDATIONS.get(pattern.id)
        if mapping is None:
            continue
        rec_id, title, description, category = mapping
        if rec_id in seen or rec_id in existing:
            continue
        seen.add(rec_id)
        recommendations.append(_rec(rec_id, title, description, category))
        if len(recommendations) >= _MAX_RECOMMENDATIONS:
            break

    if not recommendations:
        recommendations.append(
            _rec(
                "general_grounding",
                "A brief grounding pause",
                "When you have a moment, try five slow breaths and notice what you "
                "can see, hear and feel. Keep logging so patterns can be spotted "
                "when there is enough data.",
                "MINDFULNESS",
            )
        )

    note = _DISCLAIMER_NOTE
    if payload.coverage.activity_days == 0 and payload.coverage.sleep_days == 0:
        note += " Coverage is currently too sparse for physical patterns."

    return PhysicalInsightResponse(
        recommendations=recommendations, note=note, generated_by="rules"
    )


# ── Optional generative wording ────────────────────────────────────────────
#
# The patterns are still detected by the deterministic backend engine. This
# path only rewrites the *wording* of suggestions that are already grounded in
# a detected pattern. Output is rejected unless it is free of invented numbers,
# medical claims, restriction advice and duplicate recommendation ids.

_ALLOWED_CATEGORIES = {
    "SLEEP",
    "ACTIVITY",
    "HYDRATION",
    "MENTAL_WELLBEING",
    "RECOVERY",
    "MINDFULNESS",
    "WELLNESS",
}
_BANNED_TERMS = (
    "diagnos",
    "prescrib",
    "medication",
    "dosage",
    "disorder",
    "cure",
    "calorie",
    "skip meals",
    "sleep restriction",
    "force yourself",
)
_WORDING_NOTE = (
    "AI-generated supportive wording grounded in your detected patterns. No "
    "measurements were invented and no medical assessment was made."
)

_WORDING_SCHEMA = {
    "type": "OBJECT",
    "properties": {
        "recommendations": {
            "type": "ARRAY",
            "items": {
                "type": "OBJECT",
                "properties": {
                    "id": {"type": "STRING"},
                    "title": {"type": "STRING"},
                    "description": {"type": "STRING"},
                    "category": {"type": "STRING"},
                },
                "required": ["id", "title", "description", "category"],
            },
        }
    },
    "required": ["recommendations"],
}

_WORDING_SYSTEM_PROMPT = """You write short, supportive suggestions for a wellbeing app.

The backend has already detected the patterns below from the user's own data.
Rewrite supportive suggestions in warm, plain language.

Rules:
- Every suggestion must map to one of the detected pattern ids.
- Never invent a measurement, number, symptom, diagnosis, or cause.
- Do not use any digits at all.
- No calorie restriction, sleep restriction, fluid loading, exercise targets,
  medication, or diagnosis.
- Keep each title under 60 characters and each description under 240.
- Return at most three suggestions, ordered with attention patterns first.
"""


def _wording_user_block(payload: PhysicalInsightRequest) -> str:
    lines = []
    for pattern in payload.patterns:
        lines.append(
            f"- id={pattern.id}; severity={pattern.severity}; "
            f"confidence={pattern.confidence}; summary={pattern.summary}"
        )
    if not lines:
        lines.append("- no pattern detected; offer one gentle grounding suggestion")
    existing = ", ".join(payload.existing_recommendations) or "none"
    return (
        "Detected patterns (authoritative):\n"
        + "\n".join(lines)
        + f"\nAlready shown by the rule engine: {existing}\n"
    )


def _slug(value: str) -> str:
    cleaned = re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")
    return cleaned[:64] or "supportive_step"


def _validate_wording(
    raw: dict[str, Any], payload: PhysicalInsightRequest
) -> list[WellnessRecommendation] | None:
    pattern_ids = {pattern.id for pattern in payload.patterns}
    existing = set(payload.existing_recommendations)
    seen: set[str] = set()
    accepted: list[WellnessRecommendation] = []

    for item in raw.get("recommendations") or []:
        if not isinstance(item, dict):
            continue
        rec_id = _slug(str(item.get("id") or ""))
        title = str(item.get("title") or "").strip()
        description = str(item.get("description") or "").strip()
        category = str(item.get("category") or "WELLNESS").strip().upper()

        if not title or not description:
            continue
        if rec_id not in pattern_ids or rec_id in existing or rec_id in seen:
            continue
        if len(title) > 120 or len(description) > 600:
            continue
        if category not in _ALLOWED_CATEGORIES:
            category = "WELLNESS"
        text = f"{title} {description}".lower()
        if any(term in text for term in _BANNED_TERMS):
            continue
        # No digits: the model must not invent or restate measurements.
        if re.search(r"\d", f"{title} {description}"):
            continue

        seen.add(rec_id)
        accepted.append(
            WellnessRecommendation(
                id=f"llm_{rec_id}",
                title=title,
                description=description,
                category=category,
                source="AI_SERVICE",
            )
        )
        if len(accepted) >= _MAX_RECOMMENDATIONS:
            break

    return accepted or None


async def recommend_with_llm(
    payload: PhysicalInsightRequest, llm: LLMClient | None = None
) -> PhysicalInsightResponse:
    """Deterministic recommendations, optionally re-worded by the LLM.

    Falls back to the rule wording on any transport, configuration or
    validation failure, so this endpoint can never return invented advice.
    """

    base = recommend(payload)
    if not payload.patterns:
        return base

    client = llm
    if client is None:
        try:
            client = build_llm_client()
        except Exception:  # noqa: BLE001
            return base

    try:
        if not await client.is_available():
            return base
        raw = await client.complete_json(
            _WORDING_SYSTEM_PROMPT,
            _wording_user_block(payload),
            _WORDING_SCHEMA,
            max_tokens=700,
        )
        validated = _validate_wording(raw, payload)
        if validated is None:
            log.warning("physical_wording_validation_fallback")
            return base
        return PhysicalInsightResponse(
            recommendations=validated,
            note=_WORDING_NOTE,
            generated_by="llm",
        )
    except Exception as exc:  # noqa: BLE001
        log.warning("physical_wording_llm_unavailable", error=str(exc)[:200])
        return base
